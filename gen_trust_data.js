function buildSheet(key){
  const m = META[key];
  const grid = g[m.sheet];
  if(!grid) throw new Error('sheet not found: ' + m.sheet);
  /* grid: [表头1, 表头2, ...数据行] */
  const dataRows = grid.slice(2);
  const lvList = LEVELS[m.sheet].slice();
  const rows = [];
  const levels = [];
  dataRows.forEach(r=>{
    const isBlank = r.every(v=>v===null||v==='');
    if(isBlank){ rows.push([]); levels.push(0); return; }
    const seq = r[0], name = r[1], unit = r[2];
    const v = V[name];
    if(!v) throw new Error('no demo value for: ' + name);
    if(v[0] !== unit) throw new Error('unit mismatch for ' + name + ': Excel=' + unit + ' map=' + v[0]);
    const [u, monthly, mom, cum, yoy, ytd] = v;
    rows.push([seq, name, unit, monthly, mom, cum, yoy, ytd]);
    levels.push(lvList.shift());
  });
  if(lvList.length) throw new Error('levels mismatch for ' + m.sheet + ': left=' + lvList.length);

  const kpiRows = KPIS[key].map(([label,value,unit,trend,ytd])=>{
    const num = parseFloat(trend.replace(/[^-\d.]/g,''));
    const dir = num < 0 ? 'down' : 'up';
    return `      {label:${q(label)},value:${q(value)},unit:${q(unit)},trend:${q(trend)},ytd:${q(ytd)},dir:${q(dir)},type:""}`;
  }).join(',\n');

  const rowLines = rows.map(r=>{
    if(!r.length) return '      []';
    return '      [' + r.map(q).join(',') + ']';
  }).join(',\n');

  return `  ${q(key)}: {
    name: ${q(m.sheet)},
    title: ${q(m.title)},
    subtitle: "华润信托2026指标体系",
    count: ${m.count},
    levels: [${levels.join(',')}],
    kpi: [
${kpiRows}
    ],
${HEADERS},
    rows: [
${rowLines}
    ],
${CHARTS[key]}
  }`;
}

